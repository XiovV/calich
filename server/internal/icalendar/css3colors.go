var css3ColorsByName = func() map[string]css3Color {
	m := make(map[string]css3Color, len(css3Colors))
	for _, c := range css3Colors {
		m[c.name] = c
	}
	return m
}()

// nearestCSS3Keyword returns the CSS3 keyword whose defined RGB is closest
// to (r,g,b) by squared Euclidean distance, ties broken by css3Colors'
// fixed declaration order (so the result is deterministic).
func nearestCSS3Keyword(r, g, b uint8) string {
	best := css3Colors[0]
	bestDist := squaredDistance(r, g, b, best.r, best.g, best.b)
	for _, c := range css3Colors[1:] {
		if d := squaredDistance(r, g, b, c.r, c.g, c.b); d < bestDist {
			best, bestDist = c, d
		}
	}
	return best.name
}

func squaredDistance(r1, g1, b1, r2, g2, b2 uint8) int {
	dr := int(r1) - int(r2)
	dg := int(g1) - int(g2)
	db := int(b1) - int(b2)
	return dr*dr + dg*dg + db*db
}

// css3KeywordRGB looks up keyword (case-insensitive, per CSS3) in the
// extended keyword set, reporting its exact defined RGB.
func css3KeywordRGB(keyword string) (r, g, b uint8, ok bool) {
	c, ok := css3ColorsByName[strings.ToLower(strings.TrimSpace(keyword))]
	if !ok {
		return 0, 0, 0, false
	}
	return c.r, c.g, c.b, true
}

// parseHexRGB parses a "#RRGGBB" or "#RRGGBBAA" hex string — the canonical
// form service.NormalizeColor stores an Event's color in — into its RGB
// components, discarding any alpha: RFC 7986 COLOR carries no alpha channel
// of its own.
func parseHexRGB(hexColor string) (r, g, b uint8, err error) {
	s := strings.TrimPrefix(hexColor, "#")
	if len(s) != 6 && len(s) != 8 {
		return 0, 0, 0, fmt.Errorf("invalid hex color %q", hexColor)
	}
	rv, err := strconv.ParseUint(s[0:2], 16, 8)
	if err != nil {
		return 0, 0, 0, fmt.Errorf("invalid hex color %q: %w", hexColor, err)
	}
	gv, err := strconv.ParseUint(s[2:4], 16, 8)
	if err != nil {
		return 0, 0, 0, fmt.Errorf("invalid hex color %q: %w", hexColor, err)
	}
	bv, err := strconv.ParseUint(s[4:6], 16, 8)
	if err != nil {
		return 0, 0, 0, fmt.Errorf("invalid hex color %q: %w", hexColor, err)
	}
	return uint8(rv), uint8(gv), uint8(bv), nil
}
